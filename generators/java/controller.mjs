/**
 * Java Controller 生成器
 * IR → Spring @RestController
 *
 * 输出：generated/controller/XxxController.java
 *
 * 约定：
 *   - 路径参数 :id → Spring {id}，类型由 api.pathParams 显式声明（C28 保证存在）
 *   - input  → @RequestBody
 *   - query  → 逐字段 @RequestParam（Spring 自动转 Integer / BigDecimal / enum）
 *              方法体里组装 Map<String, Object> 传给 Service
 *              → Controller 对外契约类型化；Service 签名保持稳定
 *   - auth.roles → @PreAuthorize("hasAnyRole(...)")
 *   - 调用同名 Service 接口，返回 ApiResponse<Output>
 *
 * 为什么 Controller 逐字段、Service 用 Map：
 *   - Controller 是 HTTP 边界，Spring 需要按字段名做绑定 + 类型转换
 *   - Service 是内部契约，签名稳定才能不破坏已手写的 Impl
 *   - OpenAPI 文档从 IR 生成（generators/openapi/index.mjs），与 Controller 注解无关
 */
import { writeFileSync, mkdirSync, existsSync } from 'fs'
import { join } from 'path'

const HEADER = [
  '// AUTO-GENERATED by polyforge. DO NOT EDIT.',
  '// 源：模型定义的 api 段',
  '',
]

function cap(s) { return s.charAt(0).toUpperCase() + s.slice(1) }
function camel(s) { return s.split(/[-_]/).filter(Boolean).map(cap).join('') }
function serviceName(domain) { return camel(domain) + 'Service' }
function serviceVar(domain) {
  const c = camel(domain)
  return c.charAt(0).toLowerCase() + c.slice(1) + 'Service'
}

/** 基础类型 → Java 类型（供 pathParams / query 使用） */
const PRIM = {
  id: 'String',  // query 里的 id 按 String（build-ir 对 query 不解析 idType）
  string: 'String', text: 'String',
  int: 'Integer', long: 'Long',
  number: 'BigDecimal', decimal: 'BigDecimal',
  boolean: 'Boolean',
  date: 'LocalDate',
  datetime: 'OffsetDateTime',
}

/** query 字段 → Java 类型（C29 保证只有 primitive 或 enum） */
function queryFieldJavaType(fd) {
  if (fd.resolved?.kind === 'enum') return fd.resolved.target
  const t = PRIM[fd.type]
  if (!t) throw new Error('无法映射 query 字段类型: ' + fd.type)
  return t
}

function pathParams(path) {
  const names = []
  const re = /:([a-zA-Z][a-zA-Z0-9]*)/g
  let m
  while ((m = re.exec(path)) !== null) names.push(m[1])
  return names
}

/** 路径参数的 Java 类型。C28 保证每个路径参数都在 pathParams 声明。 */
function pathParamJavaType(api, name) {
  const def = api.pathParams[name]
  if (def.type === 'id') {
    return (def.idType === 'string' || def.idType === 'uuid') ? 'String' : 'Long'
  }
  const t = PRIM[def.type]
  if (!t) {
    throw new Error('无法映射路径参数类型: api ' + api.name + ' :' + name + ' = ' + def.type)
  }
  return t
}

/** /tenders/:id → /tenders/{id} */
function springPath(path) {
  return path.replace(/:([a-zA-Z][a-zA-Z0-9]*)/g, '{$1}')
}

const MAPPING = {
  GET: 'GetMapping', POST: 'PostMapping',
  PUT: 'PutMapping', PATCH: 'PatchMapping', DELETE: 'DeleteMapping',
}

function methodAnnotation(api) {
  const m = (api.method || 'GET').toUpperCase()
  return '@' + (MAPPING[m] || 'RequestMapping') + '("' + springPath(api.path) + '")'
}

function preAuthorize(api) {
  const auth = api.auth
  if (!auth || auth === 'public') return null
  if (auth === 'authenticated') return '@PreAuthorize("isAuthenticated()")'
  if (typeof auth === 'object' && Array.isArray(auth.roles) && auth.roles.length > 0) {
    const roles = auth.roles.map((r) => "'" + r.toUpperCase() + "'").join(', ')
    return '@PreAuthorize("hasAnyRole(' + roles + ')")'
  }
  return null
}

/** 方法参数：路径参数 → input → query 逐字段 */
function controllerParams(api) {
  const ps = []
  for (const p of pathParams(api.path)) ps.push('@PathVariable ' + pathParamJavaType(api, p) + ' ' + p)
  if (api.input) ps.push('@RequestBody ' + api.input + ' form')
  if (api.query) {
    for (const [fn, fd] of Object.entries(api.query)) {
      const t = queryFieldJavaType(fd)
      const req = fd.nullable ? '@RequestParam(required = false) ' : '@RequestParam '
      ps.push(req + t + ' ' + fn)
    }
  }
  return ps
}

/** 传给 Service 的实参列表（query 整体作为 Map 传） */
function callArgs(api) {
  const args = []
  for (const p of pathParams(api.path)) args.push(p)
  if (api.input) args.push('form')
  if (api.query) args.push('query')
  return args.join(', ')
}

function esc(s) { return String(s || '').replace(/"/g, '\\"') }

function groupByDomain(apis) {
  const map = new Map()
  for (const api of apis) {
    const d = api.domain
    if (!map.has(d)) map.set(d, [])
    map.get(d).push(api)
  }
  return map
}

function renderController(domain, apis, PKG, PKG_SERVICE, PKG_DTO, PKG_RESP) {
  const name = camel(domain) + 'Controller'
  const svc = serviceName(domain)
  const svcVar = serviceVar(domain)

  const lines = [...HEADER]
  lines.push('package ' + PKG + ';')
  lines.push('')
  lines.push('import ' + PKG_SERVICE + '.' + svc + ';')
  lines.push('import ' + PKG_RESP + '.ApiResponse;')

  const imports = new Set()
  for (const api of apis) {
    if (api.input) imports.add(PKG_DTO + '.' + api.input)
    if (api.output) imports.add(PKG_DTO + '.' + api.output)
  }
  for (const imp of [...imports].sort()) lines.push('import ' + imp + ';')

  lines.push('import org.springframework.web.bind.annotation.*;')
  if (apis.some((a) => preAuthorize(a))) {
    lines.push('import org.springframework.security.access.prepost.PreAuthorize;')
  }
  // query 字段类型 + query Map 容器需要的 import
  const queryTypes = new Set()
  let needsQueryMap = false
  for (const a of apis) {
    if (a.query) needsQueryMap = true
    for (const fd of Object.values(a.query || {})) {
      const t = queryFieldJavaType(fd)
      if (t === 'BigDecimal') queryTypes.add('java.math.BigDecimal')
      else if (t === 'LocalDate') queryTypes.add('java.time.LocalDate')
      else if (t === 'OffsetDateTime') queryTypes.add('java.time.OffsetDateTime')
      else if (fd.resolved?.kind === 'enum') queryTypes.add(PKG_DTO.replace(/\.dto$/, '.enums') + '.' + t)
    }
  }
  if (apis.some((a) => pathParams(a.path).some((p) => pathParamJavaType(a, p) === 'BigDecimal'))) {
    queryTypes.add('java.math.BigDecimal')
  }
  for (const imp of [...queryTypes].sort()) lines.push('import ' + imp + ';')
  lines.push('')

  lines.push('@RestController')
  lines.push('public class ' + name + ' {')
  lines.push('')
  lines.push('    private final ' + svc + ' ' + svcVar + ';')
  lines.push('')
  lines.push('    public ' + name + '(' + svc + ' ' + svcVar + ') {')
  lines.push('        this.' + svcVar + ' = ' + svcVar + ';')
  lines.push('    }')

  for (const api of apis) {
    const out = api.output || 'Void'
    const pa = preAuthorize(api)
    const params = controllerParams(api)
    const args = callArgs(api)

    lines.push('')
    lines.push('    /** ' + (api.summary || api.name) + ' */')
    lines.push('    ' + methodAnnotation(api))
    if (pa) lines.push('    ' + pa)
    lines.push('    public ApiResponse<' + out + '> ' + api.name + '(' + params.join(', ') + ') {')
    // query 逐字段 → 组装 Map 传给 Service
    if (api.query) {
      lines.push('        java.util.Map<String, Object> query = new java.util.HashMap<>();')
      for (const fn of Object.keys(api.query)) {
        lines.push('        query.put("' + fn + '", ' + fn + ');')
      }
    }
    if (api.output) {
      lines.push('        return ApiResponse.success("' + esc(api.summary || '操作成功') + '", ' + svcVar + '.' + api.name + '(' + args + '));')
    } else {
      lines.push('        ' + svcVar + '.' + api.name + '(' + args + ');')
      lines.push('        return ApiResponse.success("' + esc(api.summary || '操作成功') + '");')
    }
    lines.push('    }')
  }

  lines.push('}')
  return lines.join('\n') + '\n'
}

export function generateJavaController(ir, outRoot, basePackage) {
  const PKG = basePackage + '.generated.controller'
  const PKG_SERVICE = basePackage + '.generated.service'
  const PKG_DTO = basePackage + '.generated.dto'
  const PKG_RESP = basePackage + '.dtos'
  const dir = join(outRoot, 'controller')
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true })

  const byDomain = groupByDomain(ir.apis)
  let count = 0
  for (const [domain, apis] of byDomain) {
    const name = camel(domain) + 'Controller'
    writeFileSync(join(dir, name + '.java'), renderController(domain, apis, PKG, PKG_SERVICE, PKG_DTO, PKG_RESP), 'utf-8')
    count++
  }
  console.log('  [java/controller] ' + count + ' 个 Controller → ' + dir)
}
