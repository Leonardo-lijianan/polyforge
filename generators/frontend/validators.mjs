/**
 * 前端校验器生成器
 *
 * 输入：IR（含 rules + views）
 * 输出：formRules.ts（Element Plus 表单规则）
 *
 * 规则来源：契约 global/rules.yaml 定义的命名校验规则。
 * 视图字段通过 `validate: <ruleName>` 引用。
 */
import { writeFileSync, mkdirSync } from 'fs'
import { join } from 'path'

/**
 * 生成 formRules.ts
 * @param {object} ir   buildIR() 产出的 IR
 * @param {string} outDir 输出目录
 */
export function generateFrontendValidators(ir, outDir) {
  const rules = ir.rules
  const views = ir.views
  const groups = []
  const usedRules = new Set()

  for (const [name, v] of views) {
    if (v.viewKind !== 'form') continue
    const fields = []
    const requiredSet = new Set(v.required || [])

    for (const [fn, fd] of Object.entries(v.fields || {})) {
      const fieldRules = []

      // required
      if (requiredSet.has(fn)) {
        fieldRules.push("{ required: true, message: '请输入" + fn + "', trigger: 'blur' }")
      }

      // validateRef（字段间校验）：跳过，组件里用 @core/utils/validators 的 validateConfirmPassword

      // validate（引用命名规则 或 内联对象）
      const v = fd.validate
      if (typeof v === 'string') {
        const r = rules.get(v)
        if (r) {
          usedRules.add(v)
          fieldRules.push('...' + v + 'Rules')
        }
      } else if (v && typeof v === 'object') {
        fieldRules.push(...objectToElementPlus(v))
      }

      if (fieldRules.length > 0) {
        fields.push('  ' + fn + ': [' + fieldRules.join(', ') + ']')
      }
    }

    if (fields.length > 0) {
      groups.push('export const ' + name + 'Rules = {\n' + fields.join(',\n') + '\n}')
    }
  }

  const lines = []
  lines.push('// AUTO-GENERATED by polyforge. DO NOT EDIT.')
  lines.push('// 源：契约 global/rules.yaml + 视图 validate 引用')
  lines.push('')

  // 命名规则段（一处定义，所有表单共享）
  if (usedRules.size > 0) {
    lines.push('// ============ 命名校验规则（来自 global/rules.yaml） ============')
    for (const name of [...usedRules].sort()) {
      const r = rules.get(name)
      const parts = ruleToElementPlus(r)
      lines.push('export const ' + name + 'Rules = [' + parts.join(', ') + ']')
    }
    lines.push('')
  }

  // 表单规则段（引用命名规则）
  lines.push('// ============ 表单规则（引用命名规则） ============')
  lines.push(...groups)
  lines.push('')

  mkdirSync(outDir, { recursive: true })
  const out = join(outDir, 'formRules.ts')
  writeFileSync(out, lines.join('\n'), 'utf-8')
  console.log('  [frontend/validators] ' + usedRules.size + ' 命名规则 + ' + groups.length + ' 表单规则 → ' + out)
}

/** 契约 rule 定义 → Element Plus rule 片段数组 */
function ruleToElementPlus(r) {
  const out = []
  const msg = r.message || '格式不正确'
  if (r.pattern) {
    out.push('{ pattern: /' + escapeRegexForJs(r.pattern) + '/, message: ' + JSON.stringify(msg) + ", trigger: 'blur' }")
  }
  if (r.minLength !== undefined || r.maxLength !== undefined) {
    const parts = []
    if (r.minLength !== undefined) parts.push('min: ' + r.minLength)
    if (r.maxLength !== undefined) parts.push('max: ' + r.maxLength)
    out.push('{ ' + parts.join(', ') + ', message: ' + JSON.stringify(msg) + ", trigger: 'blur' }")
  }
  if (r.min !== undefined || r.max !== undefined) {
    const parts = ["type: 'number'"]
    if (r.min !== undefined) parts.push('min: ' + r.min)
    if (r.max !== undefined) parts.push('max: ' + r.max)
    out.push('{ ' + parts.join(', ') + ', message: ' + JSON.stringify(msg) + ", trigger: 'blur' }")
  }
  return out
}

/** 内联 validate 对象 → Element Plus rule 片段数组 */
function objectToElementPlus(v) {
  return ruleToElementPlus({
    pattern: v.pattern,
    minLength: v.minLength,
    maxLength: v.maxLength,
    min: v.min,
    max: v.max,
    message: v.message,
  })
}

/** 把契约里的 pattern 字符串安全嵌进 JS 正则字面量 */
function escapeRegexForJs(p) {
  // 契约用单引号 YAML 字符串，反斜杠已按字面传入；直接原样嵌入即可。
  // 仅把 '/' 转义，避免截断正则字面量。
  return String(p).replace(/\//g, '\\/')
}
